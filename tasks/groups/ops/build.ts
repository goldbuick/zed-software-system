import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'

import { def, handler, tasksonly } from '../../helpers'
import type { TaskContext, TaskDef } from '../../types'

const SLUR_TERMS_DEFAULT_PATH = '.slurterms.local'
const SLUR_DIGESTS_PATH = path.join('zss', 'feature', 'slurfilterdigests.ts')

function readinputpath(args: string[]): string {
  const at = args.indexOf('--input')
  if (at < 0) {
    return SLUR_TERMS_DEFAULT_PATH
  }
  const value = args[at + 1]
  if (!value) {
    throw new Error('--input needs a path')
  }
  return value
}

async function buildslurfilter(ctx: TaskContext): Promise<number> {
  const { SLUR_FILTER_TIER_LIST, slurfilterfold, slurfilterhash } =
    await import('zss/feature/slurfilter')

  const inputpath = path.resolve(ctx.root, readinputpath(ctx.args))
  if (!existsSync(inputpath)) {
    console.error(`missing word list at ${inputpath}`)
    return 1
  }

  const entries = new Map<string, string>()
  const bigrams = new Set<string>()
  const labels = new Set<string>()
  const counts: Record<string, number> = {}
  const rows = readFileSync(inputpath, 'utf8').split('\n')
  for (let i = 0; i < rows.length; ++i) {
    const row = rows[i].trim()
    if (!row || row.startsWith('#')) {
      continue
    }
    const [kind, ...words] = row.split(/\s+/)
    const folded = words.map((word) => slurfilterfold(word))
    if (kind === 'allow') {
      if (folded.length !== 2) {
        console.error(`line ${i + 1}: allow needs exactly two words`)
        return 1
      }
      bigrams.add(slurfilterhash(folded.join(' ')))
      continue
    }
    if (kind === 'allowlabel') {
      if (folded.length !== 1) {
        console.error(`line ${i + 1}: allowlabel needs exactly one word`)
        return 1
      }
      labels.add(slurfilterhash(folded[0]))
      continue
    }
    if (!(SLUR_FILTER_TIER_LIST as string[]).includes(kind)) {
      console.error(`line ${i + 1}: unknown tier`)
      return 1
    }
    if (folded.length !== 1) {
      console.error(`line ${i + 1}: expected <tier> <word>`)
      return 1
    }
    const digest = slurfilterhash(folded[0])
    if (entries.has(digest)) {
      console.error(`line ${i + 1}: duplicate word`)
      return 1
    }
    entries.set(digest, kind)
    counts[kind] = (counts[kind] ?? 0) + 1
  }

  const sortedentries = [...entries.entries()].sort((a, b) =>
    a[0].localeCompare(b[0]),
  )
  const lines = [
    '// Generated by `yarn task run ops:slurfilter:build` from a local word list',
    '// that is never committed. Do not edit by hand.',
    '',
    'export const SLUR_FILTER_ENTRIES: [string, string][] = [',
    ...sortedentries.map(([digest, tier]) => `  ['${digest}', '${tier}'],`),
    ']',
    '',
    'export const SLUR_FILTER_ALLOW_BIGRAMS: string[] = [',
    ...[...bigrams].sort().map((digest) => `  '${digest}',`),
    ']',
    '',
    'export const SLUR_FILTER_ALLOW_LABELS: string[] = [',
    ...[...labels].sort().map((digest) => `  '${digest}',`),
    ']',
    '',
  ]
  writeFileSync(path.join(ctx.root, SLUR_DIGESTS_PATH), lines.join('\n'))

  console.log(
    `wrote ${SLUR_DIGESTS_PATH}: ${SLUR_FILTER_TIER_LIST.map((tier) => `${tier}=${counts[tier] ?? 0}`).join(' ')} allow=${bigrams.size} allowlabel=${labels.size}`,
  )
  return 0
}

export const OPS_BUILD_TASKS: TaskDef[] = [
  tasksonly(
    'ops:build',
    'Build ops native artifacts (daisy) and regen committed fixtures',
    [
      'ops:daisy:build',
      'ops:fixtures:content:book:build:all',
      'ops:fixtures:synth:regen:all',
    ],
    { tags: ['slow'] },
  ),
  def('ops:slurfilter:build', {
    description:
      'Hash the local word list (.slurterms.local, gitignored; --input <path> to override) into zss/feature/slurfilterdigests.ts. Never prints words.',
    run: handler(buildslurfilter),
  }),
]
