/** Union #### command anchors from every module page (name -> heading slug). */
export function collectallmodulecommandanchors(root: string): Map<string, string> {
  const map = new Map<string, string>()
  const paths = firmwarecatalogpaths(root)
  for (let i = 0; i < paths.modules.length; i++) {
    const mod = paths.modules[i]
    const existing = readorempty(mod.path)
    if (!existing) {
      continue
    }
    const anchors = parsecommandcategoryanchors(handmdxaftercatalog(existing))
    for (const [name, slug] of anchors) {
      map.set(name, slug)
    }
  }
  return map
}

function handmdxaftercatalog(filetext: string): string {
  const end = filetext.indexOf(CATALOG_END)
  if (end < 0) {
    return filetext
  }
  return filetext.slice(end + CATALOG_END.length)
}

/** Generated block between firmware-catalog markers (no trailing newline). */
export function rendermodulecatalogblock(
  rows: FIRMWARE_CATALOG_ROW[],
  categoryanchors: Map<string, string> = new Map(),
): string {
  return [
    `{/* ${GENERATED_BANNER} */}`,
    '',
    '<a id="module-commands"></a>',
    '',
    `## All commands (${rows.length})`,
    '',
    wherelegend(),
    '',
    rendercommandtable(rows, false, categoryanchors),
  ].join('\n')
}

export function splicefirmwarecatalog(
  filetext: string,
  block: string,
): string {
  const begin = filetext.indexOf(CATALOG_BEGIN)
  const end = filetext.indexOf(CATALOG_END)
  if (begin < 0 || end < 0 || end < begin) {
    throw new Error(
      `missing ${CATALOG_BEGIN} / ${CATALOG_END} markers in firmware module doc`,
    )
  }
  const before = filetext.slice(0, begin + CATALOG_BEGIN.length)
  const after = filetext.slice(end)
  return `${before}\n${block}\n${after}`
}

export function firmwarecatalogpaths(root: string): {
  overview: string
  modules: {
    id: string
    firmwareid: string
    modulepath: string
    path: string
  }[]
} {
  const docs = join(root, 'zss/firmware/docs')
  return {
    overview: join(docs, 'index.mdx'),
    modules: firmwaremodulepages().map((page) => ({
      ...page,
      path: join(docs, `${page.id}.mdx`),
    })),
  }
}

export function writefirmwarecatalogdocs(root: string): void {
  const rows = collectfirmwarecatalog()
  const paths = firmwarecatalogpaths(root)
  const allanchors = collectallmodulecommandanchors(root)
  writeFileSync(
    paths.overview,
    renderfirmwareoverviewmdx(rows, allanchors),
    'utf8',
  )
  for (let i = 0; i < paths.modules.length; i++) {
    const mod = paths.modules[i]
    const filtered = catalogrowsformodule(mod.firmwareid, rows)
    const existing = readFileSync(mod.path, 'utf8')
    const anchors = parsecommandcategoryanchors(handmdxaftercatalog(existing))
    const next = splicefirmwarecatalog(
      existing,
      rendermodulecatalogblock(filtered, anchors),
    )
    writeFileSync(mod.path, next, 'utf8')
  }
}

function readorempty(path: string): string {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return ''
  }
}

export function checkfirmwarecatalogdocs(root: string): boolean {
  const rows = collectfirmwarecatalog()
  const paths = firmwarecatalogpaths(root)
  const allanchors = collectallmodulecommandanchors(root)
  if (
    readorempty(paths.overview) !==
    renderfirmwareoverviewmdx(rows, allanchors)
  ) {
    return false
  }
  for (let i = 0; i < paths.modules.length; i++) {
    const mod = paths.modules[i]
    const existing = readorempty(mod.path)
    if (!existing) {
      return false
    }
    let expected: string
    try {
      const anchors = parsecommandcategoryanchors(handmdxaftercatalog(existing))
      expected = splicefirmwarecatalog(
        existing,
        rendermodulecatalogblock(
          catalogrowsformodule(mod.firmwareid, rows),
          anchors,
        ),
      )
    } catch {
      return false
    }
    if (existing !== expected) {
      return false
    }
  }
  return true
}
