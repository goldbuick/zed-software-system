/**
 * Generated firmware command docs for Blume (/docs/firmware).
 * Source of truth: firmwarelistcommands / getcommandargs in zss/firmware/runner.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import {
  DRIVER_TYPE,
  firmwarecommandmodulepath,
  firmwaregetcommandargs,
  firmwarelistcommands,
} from 'zss/firmware/runner'

export type FIRMWARE_WHERE = {
  cli: boolean
  loader: boolean
  runtime: boolean
}

export type FIRMWARE_CATALOG_ROW = {
  name: string
  description: string
  where: FIRMWARE_WHERE
  /** Blume path for the owning firmware module page. */
  modulepath: string
}

const GENERATED_BANNER =
  'Generated by `yarn task docs` (firmware command catalog). Do not edit by hand.'

function escmd(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function commanddescription(name: string): string {
  const drivers = [DRIVER_TYPE.CLI, DRIVER_TYPE.RUNTIME, DRIVER_TYPE.LOADER]
  for (let i = 0; i < drivers.length; i++) {
    const args = firmwaregetcommandargs(drivers[i], name)
    if (!args || args.length === 0) {
      continue
    }
    const last = args[args.length - 1]
    if (typeof last === 'string' && last.trim().length > 0) {
      return last.trim()
    }
  }
  throw new Error(
    `firmware command #${name} has no description string in COMMAND_ARGS_SIGNATURE`,
  )
}

export function collectfirmwarecatalog(): FIRMWARE_CATALOG_ROW[] {
  const cli = new Set(firmwarelistcommands(DRIVER_TYPE.CLI))
  const loader = new Set(firmwarelistcommands(DRIVER_TYPE.LOADER))
  const runtime = new Set(firmwarelistcommands(DRIVER_TYPE.RUNTIME))
  const names = [...new Set([...cli, ...loader, ...runtime])].sort((a, b) =>
    a.localeCompare(b),
  )
  return names.map((name) => {
    const modulepath = firmwarecommandmodulepath(name)
    if (!modulepath) {
      throw new Error(
        `firmware command #${name} is not registered on any FIRMWARE module`,
      )
    }
    return {
      name,
      description: commanddescription(name),
      where: {
        cli: cli.has(name),
        loader: loader.has(name),
        runtime: runtime.has(name),
      },
      modulepath,
    }
  })
}

function wherebadges(where: FIRMWARE_WHERE): string {
  const parts: string[] = []
  if (where.cli) {
    parts.push('<span class="fw-where fw-where-cli">C</span>')
  }
  if (where.loader) {
    parts.push('<span class="fw-where fw-where-loader">L</span>')
  }
  if (where.runtime) {
    parts.push('<span class="fw-where fw-where-runtime">R</span>')
  }
  return `<span class="fw-where-cell">${parts.join('')}</span>`
}

function wherelegend(): string {
  return [
    '<p class="fw-where-legend">',
    '<span class="fw-where fw-where-cli">C</span> CLI - terminal / operator',
    '<span class="fw-where fw-where-loader">L</span> Loader - import',
    '<span class="fw-where fw-where-runtime">R</span> Runtime - codepages',
    '</p>',
  ].join(' ')
}

export function renderfirmwareoverviewmdx(
  rows: FIRMWARE_CATALOG_ROW[] = collectfirmwarecatalog(),
): string {
  const table = [
    '| Command | Where | Description |',
    '|--------|-------|-------------|',
    ...rows.map((row) => {
      const link = `[\`#${escmd(row.name)}\`](${row.modulepath})`
      return `| ${link} | ${wherebadges(row.where)} | ${escmd(row.description)} |`
    }),
  ].join('\n')

  return [
    '---',
    'title: Overview',
    'description: Firmware is the #command vocabulary — every command with CLI / Loader / Runtime where it runs.',
    '---',
    '',
    `{/* ${GENERATED_BANNER} */}`,
    '',
    'Firmware is how Zed Cafe turns `#command` text into work: books and pages in the terminal, boards and objects while a world runs, and imports while content loads.',
    '',
    '## Drivers',
    '',
    '| Driver | When | Firmwares |',
    '|--------|------|-----------|',
    '| **CLI** | Terminal / operator input | `cli` + standard library |',
    '| **RUNTIME** | Codepage chips on a board | `runtime` + standard library |',
    '| **LOADER** | Importing files into books | `loader` + standard library |',
    '',
    '**Standard library** (every driver): `audio`, `board`, `network`, `transform`, `element`. Permission checks apply to the **CLI** driver only.',
    '',
    'Module notes: [CLI](/firmware/cli) · [Runtime](/firmware/runtime) · [Loader](/firmware/loader).',
    '',
    // Markdown ## so Blume TOC picks it up; explicit id keeps #all-commands stable
    // when the count changes (slug would otherwise include the number).
    '<a id="all-commands"></a>',
    '',
    `## All commands (${rows.length})`,
    '',
    wherelegend(),
    '',
    table,
    '',
    '## Modules',
    '',
    '| Doc | Purpose |',
    '|-----|---------|',
    '| [Audio](/firmware/audio) | `#play`, `#bgplay`, TTS, synth, FX |',
    '| [Board](/firmware/board) | Place, shoot, duplicate, board helpers |',
    '| [CLI](/firmware/cli) | Books, pages, export, multiplayer, ZNS |',
    '| [Element](/firmware/element) | Stats, movement, lifecycle, `#run` |',
    '| [Loader](/firmware/loader) | Import context; text, JSON, and binary readers |',
    '| [Network](/firmware/network) | HTTP fetch |',
    '| [Runtime](/firmware/runtime) | Messaging, UI, gadget |',
    '| [Transforms](/firmware/transforms) | Snapshot, copy, remix, weave, pivot |',
    '',
  ].join('\n')
}

export function firmwarecatalogpaths(root: string): {
  overview: string
} {
  return {
    overview: join(root, 'zss/firmware/docs/index.mdx'),
  }
}

export function writefirmwarecatalogdocs(root: string): void {
  const rows = collectfirmwarecatalog()
  const paths = firmwarecatalogpaths(root)
  writeFileSync(paths.overview, renderfirmwareoverviewmdx(rows), 'utf8')
}

function readorempty(path: string): string {
  try {
    return readFileSync(path, 'utf8')
  } catch {
    return ''
  }
}

export function checkfirmwarecatalogdocs(root: string): boolean {
  const rows = collectfirmwarecatalog()
  const paths = firmwarecatalogpaths(root)
  return readorempty(paths.overview) === renderfirmwareoverviewmdx(rows)
}
