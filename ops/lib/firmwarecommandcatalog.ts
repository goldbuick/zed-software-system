/**
 * Generated firmware command docs for Blume (/docs/firmware).
 * Source of truth: firmwarelistcommands / getcommandargs in zss/firmware/runner.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import {
  DRIVER_TYPE,
  firmwarecommandmodulepath,
  firmwaregetcommandargs,
  firmwarelistcommands,
  firmwaremoduledocids,
  firmwaremoduledocpath,
  firmwaremodulelistcommands,
} from 'zss/firmware/runner'

export type FIRMWARE_WHERE = {
  cli: boolean
  loader: boolean
  runtime: boolean
}

export type FIRMWARE_CATALOG_ROW = {
  name: string
  description: string
  where: FIRMWARE_WHERE
  /** Blume path for the owning firmware module page. */
  modulepath: string
}

const GENERATED_BANNER =
  'Generated by `yarn task docs` (firmware command catalog). Do not edit by hand.'

const CATALOG_BEGIN = '{/* firmware-catalog:begin */}'
const CATALOG_END = '{/* firmware-catalog:end */}'

/** Published sidebar modules (Blume page id -> path). Doc id may differ from firmware id (transform -> transforms). */
export function firmwaremodulepages(): {
  id: string
  firmwareid: string
  modulepath: string
}[] {
  return firmwaremoduledocids().map((firmwareid) => {
    const modulepath = firmwaremoduledocpath(firmwareid)
    if (!modulepath) {
      throw new Error(`missing docs path for firmware module ${firmwareid}`)
    }
    const id = modulepath.replace(/^\/firmware\//, '')
    return { id, firmwareid, modulepath }
  })
}

function escmd(value: string): string {
  return value.replace(/\|/g, '\\|').replace(/\n/g, ' ')
}

function commanddescription(name: string): string {
  const drivers = [DRIVER_TYPE.CLI, DRIVER_TYPE.RUNTIME, DRIVER_TYPE.LOADER]
  for (let i = 0; i < drivers.length; i++) {
    const args = firmwaregetcommandargs(drivers[i], name)
    if (!args || args.length === 0) {
      continue
    }
    const last = args[args.length - 1]
    if (typeof last === 'string' && last.trim().length > 0) {
      return last.trim()
    }
  }
  throw new Error(
    `firmware command #${name} has no description string in COMMAND_ARGS_SIGNATURE`,
  )
}

export function collectfirmwarecatalog(): FIRMWARE_CATALOG_ROW[] {
  const cli = new Set(firmwarelistcommands(DRIVER_TYPE.CLI))
  const loader = new Set(firmwarelistcommands(DRIVER_TYPE.LOADER))
  const runtime = new Set(firmwarelistcommands(DRIVER_TYPE.RUNTIME))
  const names = [...new Set([...cli, ...loader, ...runtime])].sort((a, b) =>
    a.localeCompare(b),
  )
  return names.map((name) => {
    const modulepath = firmwarecommandmodulepath(name)
    if (!modulepath) {
      throw new Error(
        `firmware command #${name} is not registered on any FIRMWARE module`,
      )
    }
    return {
      name,
      description: commanddescription(name),
      where: {
        cli: cli.has(name),
        loader: loader.has(name),
        runtime: runtime.has(name),
      },
      modulepath,
    }
  })
}

/**
 * Rows for a module page: every command that firmware registers.
 * Where/description come from the driver union catalog (by name).
 * Differs from overview ownership (first match in module order).
 */
export function catalogrowsformodule(
  firmwareid: string,
  rows: FIRMWARE_CATALOG_ROW[] = collectfirmwarecatalog(),
): FIRMWARE_CATALOG_ROW[] {
  const byname = new Map(rows.map((row) => [row.name, row]))
  const names = firmwaremodulelistcommands(firmwareid)
  return names.map((name) => {
    const row = byname.get(name)
    if (!row) {
      throw new Error(
        `firmware module ${firmwareid} registers #${name} but it is missing from the driver catalog`,
      )
    }
    return row
  })
}

function wherebadges(where: FIRMWARE_WHERE): string {
  const parts: string[] = []
  if (where.cli) {
    parts.push('<span class="fw-where fw-where-cli">C</span>')
  }
  if (where.loader) {
    parts.push('<span class="fw-where fw-where-loader">L</span>')
  }
  if (where.runtime) {
    parts.push('<span class="fw-where fw-where-runtime">R</span>')
  }
  return `<span class="fw-where-cell">${parts.join('')}</span>`
}

function wherelegend(): string {
  return [
    '<p class="fw-where-legend">',
    '<span class="fw-where fw-where-cli">C</span> CLI - terminal / operator',
    '<span class="fw-where fw-where-loader">L</span> Loader - import',
    '<span class="fw-where fw-where-runtime">R</span> Runtime - codepages',
    '</p>',
  ].join(' ')
}

/** Blume heading id (matches rehype-slug style used on firmware docs). */
export function slugifyfirmwareheading(title: string): string {
  return title
    .toLowerCase()
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
}

function expandnumericrange(left: string, right: string): string[] {
  const a = left.replace(/^#/, '')
  const b = right.replace(/^#/, '')
  const ma = /^([a-zA-Z]+)(\d+)([a-zA-Z]*)$/.exec(a)
  const mb = /^([a-zA-Z]+)(\d+)([a-zA-Z]*)$/.exec(b)
  if (ma && mb && ma[1] === mb[1] && ma[3] === mb[3]) {
    const lo = Math.min(Number(ma[2]), Number(mb[2]))
    const hi = Math.max(Number(ma[2]), Number(mb[2]))
    const names: string[] = []
    for (let n = lo; n <= hi; n++) {
      names.push(`${ma[1]}${n}${ma[3]}`)
    }
    return names
  }
  return [a, b]
}

function commandnamesfromtokens(
  source: string,
  tokens: string[],
): string[] {
  if (tokens.length === 0) {
    return []
  }
  const hasellipsis = /…|\.\.\./.test(source)
  if (hasellipsis && tokens.length >= 2) {
    return expandnumericrange(tokens[0], tokens[tokens.length - 1])
  }
  return [...tokens]
}

function commandnamesfromcell(cell: string): string[] {
  const tokens = [...cell.matchAll(/`([^`]+)`/g)].map((m) =>
    m[1].replace(/^#/, '').trim(),
  )
  return commandnamesfromtokens(cell, tokens)
}

/** Extract #command names from a #### heading title (bare or backtick). */
export function commandnamesfromheading(title: string): string[] {
  const frombackticks = commandnamesfromcell(title)
  if (frombackticks.length > 0) {
    return frombackticks
  }
  const tokens = [...title.matchAll(/#([a-zA-Z][a-zA-Z0-9]*)/g)].map(
    (m) => m[1],
  )
  return commandnamesfromtokens(title, tokens)
}

/**
 * Map command name -> #### heading anchor (content after the generated catalog
 * block). All-commands deep-links use these command-level slugs.
 */
/** Commands listed in All commands but missing from any #### #command heading. */
export function missingcategorycommands(
  rows: FIRMWARE_CATALOG_ROW[],
  handmdx: string,
): string[] {
  const anchors = parsecommandcategoryanchors(handmdx)
  return rows
    .map((row) => row.name)
    .filter((name) => !anchors.has(name))
    .sort((a, b) => a.localeCompare(b))
}

export function parsecommandcategoryanchors(
  handmdx: string,
): Map<string, string> {
  const map = new Map<string, string>()
  const lines = handmdx.split('\n')
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]
    const heading = /^(#{4})\s+(.+)$/.exec(line)
    if (!heading) {
      continue
    }
    const title = heading[2].trim()
    const slug = slugifyfirmwareheading(title)
    const names = commandnamesfromheading(title)
    for (let n = 0; n < names.length; n++) {
      map.set(names[n], slug)
    }
  }
  return map
}

function rendercommandtable(
  rows: FIRMWARE_CATALOG_ROW[],
  linktomodule: boolean,
  categoryanchors?: Map<string, string>,
): string {
  return [
    '| Command | Where | Description |',
    '|--------|-------|-------------|',
    ...rows.map((row) => {
      const cmd = `\`#${escmd(row.name)}\``
      let cell = cmd
      if (linktomodule) {
        const anchor = categoryanchors?.get(row.name)
        cell = anchor
          ? `[${cmd}](${row.modulepath}#${anchor})`
          : `[${cmd}](${row.modulepath})`
      } else if (categoryanchors) {
        const anchor = categoryanchors.get(row.name)
        if (anchor) {
          cell = `[${cmd}](#${anchor})`
        }
      }
      return `| ${cell} | ${wherebadges(row.where)} | ${escmd(row.description)} |`
    }),
  ].join('\n')
}

